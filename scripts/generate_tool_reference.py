"""Generate the public tool reference from the checked-out MCP bridge."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def markdown_cell(value: str) -> str:
    return escape(" ".join(value.split()), quote=False).replace("|", r"\|")


def argument_names(names) -> str:
    return ", ".join(f"`{name}`" for name in names) or "—"


def render_markdown(tools: list[dict], profiles: dict[str, int]) -> str:
    categories = defaultdict(list)
    for tool in tools:
        categories[tool["category"]].append(tool)

    lines = [
        "# Blender MCP Pro tool reference",
        "",
        "<!-- Generated by scripts/generate_tool_reference.py. -->",
        "",
        f"The full MCP profile registers **{len(tools)} tools** in **{len(categories)} categories**.",
        "The bridge offers the profiles listed below. Each entry lists the inputs",
        "accepted by the registered tool. The [JSON catalog](tool-schemas.json) includes",
        "input types, defaults, profile membership, and discovery metadata.",
        "The `bridge` marker identifies discovery tools handled locally by the bridge.",
        "",
        "In a connected MCP client, call `tools_search` with a name or phrase and",
        "use `tools_describe` for the active tool's schema. `tools_catalog` can",
        "return all active tools or filter by one of the categories below.",
        "",
        "## Profiles",
        "",
        "Set `BLENDER_MCP_PROFILE` before launching the bridge. The default is",
        "`full`. An unknown name falls back to `core`. Profiles control tool",
        "registration and discovery. The add-on enforces execution permissions.",
        "",
        "| Profile | Tools |",
        "| --- | ---: |",
    ]
    first_profiles = ["full", "guided", "core", "nano"]
    for profile in first_profiles + sorted(profiles.keys() - set(first_profiles)):
        lines.append(f"| `{profile}` | {profiles[profile]} |")

    category_labels = {"qa": "QA", "hardsurface": "Hard Surface"}
    labels = {
        category: category_labels.get(category, category.replace("_", " ").title())
        for category in sorted(categories)
    }
    lines.extend(["", "## Categories", "", "| Category | Tools |", "| --- | ---: |"])
    for category, label in labels.items():
        anchor = label.lower().replace(" ", "-")
        lines.append(f"| [`{category}`](#{anchor}) | {len(categories[category])} |")

    for category, label in labels.items():
        lines.extend([
            "",
            f"## {label}",
            "",
            "| Tool | Purpose | Required arguments | Optional arguments |",
            "| --- | --- | --- | --- |",
        ])
        for tool in categories[category]:
            schema = tool["input_schema"]
            required = schema.get("required", [])
            optional = [name for name in schema.get("properties", {}) if name not in required]
            lines.append(
                f"| `{tool['name']}` | {markdown_cell(tool['description'])} "
                f"| {argument_names(required)} | {argument_names(optional)} |"
            )

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated content with the checked-in files.")
    args = parser.parse_args()

    # Profile filtering runs on import. Read the entire local checkout's registry.
    os.environ["BLENDER_MCP_PROFILE"] = "full"
    sys.path.insert(0, str(ROOT / "src"))
    from blender_mcp import server

    catalog = json.loads(server.tools_catalog(include_schema=True))
    tools = catalog["tools"]
    registered = {tool["name"] for tool in tools}
    profiles = {
        name: len(registered & allowed) if allowed is not None else len(registered)
        for name, allowed in server.TOOL_PROFILES.items()
    }
    generated = {
        DOCS / "tools.md": render_markdown(tools, profiles),
        DOCS / "tool-schemas.json": json.dumps(
            {"profiles": profiles, "tools": tools}, ensure_ascii=False, indent=2, sort_keys=True
        ) + "\n",
    }
    if args.check:
        stale = [
            str(path.relative_to(ROOT))
            for path, content in generated.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"Update {', '.join(stale)} with python scripts/generate_tool_reference.py.", file=sys.stderr)
            return 1
    else:
        for path, content in generated.items():
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Tool reference matches {len(tools)} tools and {len(profiles)} profiles.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
